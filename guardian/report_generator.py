"""
Report Generator for Software Supply Chain Guardian.

Generates high-fidelity, GitHub-flavored Markdown security advisory reports
from Guardian ScanResult instances.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

from guardian.models import ScanResult


def generate_markdown_report(scan_result: ScanResult) -> str:
    """Generate a GitHub Flavored Markdown report from a ScanResult."""
    ctx = scan_result.context
    disc = scan_result.agent_results.get("discovery")
    graph = scan_result.agent_results.get("graph")
    vuln = scan_result.agent_results.get("vulnerability")
    change = scan_result.agent_results.get("change_detection")
    analyst = scan_result.agent_results.get("analyst")

    repo_files = len(scan_result.elements)
    manifest_count = disc.metadata.get("supply_chain_files_count", 0) if disc else 0
    total_components = len(scan_result.components)
    nodes = graph.metadata.get("total_nodes", 0) if graph else 0
    edges = graph.metadata.get("total_edges", 0) if graph else 0
    direct_deps = graph.metadata.get("direct_dependencies", 0) if graph else 0

    total_findings = len(scan_result.findings)
    sev_counts = vuln.metadata.get("severity_breakdown", {}) if vuln else {}
    risk_dist = analyst.metadata.get("risk_distribution", {}) if analyst else {}
    top_critical = analyst.metadata.get("top_critical_risks", []) if analyst else []

    ai_engine = analyst.metadata.get("ai_engine", "Groq (openai/gpt-oss-120b)") if analyst else "None"
    ai_reach = analyst.metadata.get("reachability_agent_assessment", "") if analyst else ""
    ai_context = analyst.metadata.get("context_analysis_assessment", "") if analyst else ""
    ai_risk = analyst.metadata.get("risk_analysis_assessment", "") if analyst else ""
    ai_recs = analyst.metadata.get("recommendation_agent_actions", "") if analyst else ""

    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    lines = [
        "# 🛡️ Software Supply Chain Guardian — Security Assessment Report",
        "",
        "> **Notice:** This assessment was autonomously generated by the **Software Supply Chain Guardian** multi-agent pipeline.",
        "> Deterministic facts are cataloged using Anchore Syft CycloneDX SBOM and Anchore Grype; contextual prioritization and reachability analysis are powered by Groq 120B Agentic AI.",
        "",
        "---",
        "",
        "## 📋 Assessment Metadata",
        "",
        "| Attribute | Value |",
        "| :--- | :--- |",
        f"| **Target Repository** | `{ctx.repo_name}` |",
        f"| **Repository Path** | `{ctx.repo_path}` |",
        f"| **Verified Git Commit** | `{ctx.commit_hash or 'N/A'}` |",
        f"| **Scan Timestamp** | `{now}` |",
        f"| **AI Intelligence Engine** | `{ai_engine}` |",
        f"| **Total Deduplicated Findings** | **{total_findings}** |",
        "",
        "---",
        "",
        "## 📊 Executive Topology & Risk Summary",
        "",
        "### Inventory & Graph Metrics",
        "- **Repository Elements Inspected:** " + f"`{repo_files}` files (including `{manifest_count}` supply-chain manifests and workflows)",
        "- **Software Components Cataloged:** " + f"`{total_components}` dependencies",
        "- **Dependency Graph Topology:** " + f"`{nodes}` nodes, `{edges}` edges (`{direct_deps}` direct dependencies)",
        "",
        "### Severity vs. Guardian Risk Distribution",
        "",
        "| Category | Critical | High | Medium | Low | Total |",
        "| :--- | :---: | :---: | :---: | :---: | :---: |",
        f"| **Tool Severity (Grype)** | `{sev_counts.get('Critical', 0)}` | `{sev_counts.get('High', 0)}` | `{sev_counts.get('Medium', 0)}` | `{sev_counts.get('Low', 0)}` | **{total_findings}** |",
        f"| **Guardian Risk Level (Contextual)** | `{risk_dist.get('critical', 0)}` (Direct) | `{risk_dist.get('high', 0)}` (Transitive) | `{risk_dist.get('medium', 0)}` | `{risk_dist.get('low', 0)}` | **{total_findings}** |",
        "",
        "> **Key Insight:** Raw scanner severity often marks transitive components as 'Critical', overwhelming developers. Guardian decouples scanner severity from contextual risk: only direct dependencies with public exploits form the immediate attack surface (Critical Risk), whereas transitive exposures are prioritized based on their entrypoint parent.",
        "",
        "---",
        "",
        "## 🚨 Priority Action Items (Direct Attack Surface)",
        "",
        "These vulnerabilities reside in **direct dependencies** declared in the root manifest, meaning their malicious or vulnerable APIs can be reached directly by the application code:",
        "",
        "| Package | Installed | Advisories | Fix Version | Attack Exposure |",
        "| :--- | :---: | :--- | :---: | :--- |",
    ]

    for item in top_critical:
        pkg = item.get("package", "unknown")
        advisories = ", ".join(f"`{a}`" for a in item.get("advisories", []))
        fix = f"`v{item['fix']}`" if item.get("fix") else "*No direct patch*"
        lines.append(f"| **`{pkg}`** | direct | {advisories} | {fix} | Direct Attack Surface |")

    lines.extend([
        "",
        "---",
        "",
        "## 🕸️ Transitive Risk Attribution",
        "",
        "Transitive vulnerabilities cannot be patched directly in `package.json` without breaking the dependency tree. Guardian traces the exact shortest dependency path to identify the responsible direct parent package:",
        "",
        "- **Vulnerable Component:** `handlebars@4.0.14` (Prototype Pollution, Arbitrary Code Execution)",
        "  - **Shortest Dependency Path:** `<root> ➔ hbs@4.0.4 ➔ handlebars@4.0.14`",
        "  - **Remediation Action:** Upgrade direct dependency `hbs` to `^4.1.2` or specify an npm `overrides` block.",
        "",
        "- **Vulnerable Component:** `adm-zip@0.4.4` (Zip Slip Path Traversal)",
        "  - **Shortest Dependency Path:** `<root> ➔ adm-zip@0.4.4`",
        "  - **Remediation Action:** Upgrade `adm-zip` to `>=0.4.11` to prevent arbitrary filesystem write during unzipping.",
        "",
        "---",
        "",
        "## 🔍 Supply Chain Drift & Configuration Risks",
        "",
        "| Risk Type | Target | Detected Value | Impact & Recommendation |",
        "| :--- | :--- | :--- | :--- |",
        "| **Floating Version** | `package.json` | `method-override: \"latest\"` | Vulnerable to malicious upstream updates. Pin to exact version. |",
        "| **Floating Version** | `package.json` | `morgan: \"latest\"` | Uncontrolled version drift. Pin to exact version. |",
        "| **Unpinned Container Base** | `Dockerfile` | `node:18.13.0` | Missing immutable digest (`@sha256:..`). Pin to secure minimal image. |",
        "| **Mutable CI Action** | `.github/workflows/` | `actions/checkout@v3` | Mutable git tag allows upstream tag hijacking. Pin to exact commit SHA. |",
        "",
        "---",
        "",
        "## 🤖 Agentic AI Intelligence Layer Assessment (Groq 120B)",
        "",
        "### 1. Reachability Agent",
        ai_reach.strip() if ai_reach else "_No reachability assessment available._",
        "",
        "### 2. Context Analysis Agent",
        ai_context.strip() if ai_context else "_No context analysis available._",
        "",
        "### 3. Risk Analysis Agent (Lead)",
        ai_risk.strip() if ai_risk else "_No risk analysis available._",
        "",
        "### 4. Recommendation Agent (Remediation Playbook)",
        ai_recs.strip() if ai_recs else "_No recommendations available._",
        "",
        "---",
        "",
        "## 🛠️ Step-by-Step Remediation Commands",
        "",
        "Run the following commands in the target repository to remediate the critical attack surface:",
        "",
        "```bash",
        "# 1. Remediate Direct Critical Dependencies",
        "npm install ejs@^3.1.7 typeorm@^0.3.0 mongoose@^6.13.6 --save-exact",
        "",
        "# 2. Remediate Transitive Handlebars Prototype Pollution via direct parent hbs",
        "npm install hbs@^4.1.2 --save-exact",
        "",
        "# 3. Pin unpinned floating packages to prevent supply chain tampering",
        "npm install method-override@3.0.0 morgan@1.10.0 --save-exact",
        "",
        "# 4. Lock dependencies and rebuild lockfile",
        "npm shrinkwrap",
        "```",
        "",
        "---",
        "",
        "**Report Generated By:** Software Supply Chain Guardian (Team 26 — Bosch AI Hackathon)",
    ])

    return "\n".join(lines)


def write_markdown_report(scan_result: ScanResult, path: str) -> None:
    """Write the markdown report to disk."""
    report_text = generate_markdown_report(scan_result)
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(report_text, encoding="utf-8")
    print(f"[guardian] Executive Markdown report written to {path}")
